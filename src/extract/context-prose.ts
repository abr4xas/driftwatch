/**
 * La linea es una **instruccion de crear** algo, asi que la ruta es un destino
 * y no una afirmacion de existencia.
 *
 * Caso real (tursodatabase/turso): "1. Create
 * `perf/memory/src/profile/your_profile.rs` implementing the `Profile` trait".
 *
 * Solo cuenta si el imperativo abre la linea, despues de la vinieta o el
 * numero de paso. "Create" en medio de una oracion no marca nada; al principio
 * de un paso numerado, si. Esa restriccion es lo que evita suprimir de mas,
 * porque "add" y "create" aparecen por todas partes en cualquier documentacion.
 */
const IMPERATIVOS_DE_CREAR = [
  'create',
  'add',
  'new',
  'generate',
  'scaffold',
  'touch',
  'mkdir',
  'crear',
  'crea',
  'creá',
  'agregar',
  'agrega',
  'agregá',
  'añadir',
  'añade',
  'nuevo',
  'generá',
]

/** Quita vinetas, numeracion de pasos y encabezados del arranque de la linea. */
function stripListMarkers(line: string): string {
  return line.replace(/^[\s>]*(?:[-*+]|#{1,6}|\d+[.)])\s*/u, '').replace(/^\*\*/u, '')
}

function esInstruccionDeCrear(line: string): boolean {
  const head = stripListMarkers(line).toLowerCase()
  return IMPERATIVOS_DE_CREAR.some((verb) => head.startsWith(`${verb} `))
}

const MARCADORES = [...EJEMPLO, ...CUBIERTO]

/**
 * Si una linea **abre** un elemento propio en vez de continuar el anterior.
 *
 * Una fila de tabla, una vineta, un paso numerado y un encabezado son
 * afirmaciones independientes. Una oracion envuelta, en cambio, nunca empieza
 * con ninguno de esos marcadores.
 */
function opensItsOwnItem(line: string): boolean {
  return /^[\s>]*(?:\||[-*+]\s|\d+[.)]\s|#{1,6}\s)/u.test(line)
}

/**
 * La linea que contiene un offset, y la anterior **solo si esta es su
 * continuacion**.
 *
 * La linea sola no alcanza: una oracion envuelta parte el marcador de la ruta.
 * Caso real (BerriAI/litellm), donde el "such as" queda una linea arriba:
 *
 *     Use subdirectories that match the implementation path, such as
 *     `auth/test_token_exchange.py` for `auth/token_exchange.py` and
 *
 * Pero mirar la linea anterior sin condiciones sangra entre elementos que no
 * tienen nada que ver. Caso real (cyanheads/git-mcp-server), dos filas de una
 * tabla:
 *
 *     | `src/mcp-server/prompts/definitions/` | MCP Prompt definitions (e.g., ...) |
 *     | `src/mcp-server/transports/`          | Transport implementations ...      |
 *
 * El "e.g." de la primera fila suprimia la segunda, que es otra afirmacion.
 * Por eso la ventana se abre solo cuando la linea actual no abre un elemento
 * propio.
 */
export function lineAround(content: string, offset: number): string {
  const lineStart = content.lastIndexOf('\n', offset) + 1
  const end = content.indexOf('\n', offset)
  const lineEnd = end === -1 ? content.length : end
  const line = content.slice(lineStart, lineEnd)

  if (lineStart === 0 || opensItsOwnItem(line)) return line

  const previousStart = content.lastIndexOf('\n', lineStart - 2) + 1
  return content.slice(previousStart, lineEnd)
}

/**
 * Si la linea que rodea a la afirmacion la marca como ejemplo o la da por
 * incierta. Se mira la linea entera, no solo lo que va antes: un "(if exists)"
 * llega despues de la ruta.
 */
export type ProseContext = {
  /** `owner/repo` de este repo, para reconocer cuando se habla de otro. */
  origin: string | undefined
}

/**
 * Si la linea enlaza a un repositorio **distinto** de este.
 *
 * Caso real (prisma/prisma): "`drive-*` skills and [`docs/drive/`](...) live in
 * [prisma/ignite](https://github.com/prisma/ignite) (`skills/.pilot/`)". La
 * linea nombra otro repo dos veces; las rutas que menciona son de alla.
 *
 * Sin remoto conocido la regla no se aplica: no se puede saber que es "otro".
 */
function namesAnotherRepo(line: string, origin: string | undefined): boolean {
  if (origin === undefined) return false
  const lower = line.toLowerCase()
  for (const match of lower.matchAll(/(?:github|gitlab)\.com\/([^/\s)\]]+\/[^/\s)\]#?]+)/gu)) {
    const slug = (match[1] ?? '').replace(/\.git$/u, '')
    if (slug !== origin) return true
  }
  return false
}

export function proseDisclaims(line: string, ctx: ProseContext = { origin: undefined }): boolean {
  const lower = line.toLowerCase()
  if (MARCADORES.some((marker) => lower.includes(marker))) return true
  if (namesAnotherRepo(line, ctx.origin)) return true
  // El imperativo se busca por linea, no en la ventana de dos: lo que importa
  // es como abre *esta* linea.
  return line.split('\n').some(esInstruccionDeCrear)
}
